// BUG-20: generates src/environments/env.generated.ts from real process.env
// values available to the Node.js BUILD process (Netlify/CI or a local shell).
//
// Why this exists: the Angular browser bundle has no `process` global — the
// @angular/build:application builder does not inject one, and this project
// has no --define / @ngx-env/builder wiring. Any code that read
// `process.env.X` directly at runtime always evaluated to undefined in the
// deployed bundle. This script runs entirely in Node (identical behavior on
// Windows dev machines and Netlify's Linux build image — no shell quoting
// involved) and bakes the real values in as literal string constants BEFORE
// `ng build` ever runs, so the compiled bundle contains the actual values
// instead of a dead `process.env` reference.
//
// Output file is git-ignored (see .gitignore) and regenerated on every build.
// Missing env vars produce empty strings, never a build failure.

import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

import { checkDeployContext } from './lib/deploy-context-guard.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outFile = join(__dirname, '..', 'src', 'environments', 'env.generated.ts');

function readEnv(...keys) {
  for (const key of keys) {
    const value = process.env[key];
    if (typeof value === 'string' && value.trim() !== '') {
      return value.trim();
    }
  }
  return '';
}

const values = {
  GOOGLE_CLIENT_ID: readEnv('GOOGLE_CLIENT_ID'),
  APPLE_CLIENT_ID: readEnv('APPLE_CLIENT_ID'),
  APPLE_REDIRECT_URI: readEnv('APPLE_REDIRECT_URI'),
  API_URL: readEnv('API_URL'),
  BASE_URL: readEnv('BASE_URL', 'API_ORIGIN'),
  SIGNALR_URL: readEnv('SIGNALR_URL', 'NOTIFICATION_HUB_URL'),
  SITE_URL: readEnv('SITE_URL'),
  // Monetization (docs/MONETIZATION.md). Every flag is OFF unless exactly "true"; ids are never defaulted.
  ADS_ENABLED: readEnv('ADS_ENABLED'),
  WEB_ADS_ENABLED: readEnv('WEB_ADS_ENABLED'),
  ANDROID_ADS_ENABLED: readEnv('ANDROID_ADS_ENABLED'),
  IOS_ADS_ENABLED: readEnv('IOS_ADS_ENABLED'),
  ADSENSE_PUBLISHER_ID: readEnv('ADSENSE_PUBLISHER_ID'),
  ADSENSE_SLOT_SEARCH: readEnv('ADSENSE_SLOT_SEARCH'),
  ADSENSE_SLOT_DETAIL: readEnv('ADSENSE_SLOT_DETAIL'),
  ADMOB_BANNER_ANDROID: readEnv('ADMOB_BANNER_ANDROID'),
  ADMOB_BANNER_IOS: readEnv('ADMOB_BANNER_IOS'),
  // Error reports to our own API (docs/privacy in the API repo: analytics-inventory). On unless exactly "true" here.
  CLIENT_ERROR_REPORTING_DISABLED: readEnv('CLIENT_ERROR_REPORTING_DISABLED')
};

const contextProblems = checkDeployContext(
  { CONTEXT: readEnv('CONTEXT'), BRANCH: readEnv('BRANCH') },
  values
);
if (contextProblems.length > 0) {
  for (const problem of contextProblems) console.error(`[generate-env] ${problem}`);
  process.exit(1);
}

function escape(value) {
  return value.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

const lines = [
  '// AUTO-GENERATED by tools/generate-env.mjs at build time. DO NOT EDIT BY HAND.',
  '// DO NOT COMMIT — this file is git-ignored and may contain real values during a local build.',
  '// See BUG-20 in the remediation reports for why this file exists.',
  'export const generatedEnv = {',
  ...Object.entries(values).map(([key, value]) => `  ${key}: '${escape(value)}',`),
  '} as const;',
  ''
];

writeFileSync(outFile, lines.join('\n'), 'utf8');

const presentKeys = Object.entries(values)
  .filter(([, v]) => v !== '')
  .map(([k]) => k);
console.log(
  `[generate-env] wrote ${outFile} — populated keys: ${presentKeys.length ? presentKeys.join(', ') : '(none, all empty)'}`
);
