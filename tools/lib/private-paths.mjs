// The single list of URL paths that must never appear in a search result, and the two static
// artifacts derived from it: robots.txt `Disallow:` lines (tools/generate-robots.mjs) and an
// `X-Robots-Tag: noindex` response header per path (public/_headers, also written by that script).
//
// Why both: `Disallow` stops a well-behaved crawler FETCHING the URL, but it does not stop the URL
// being listed (URL only, no snippet) if something links to it -- and this app links to
// /auth/login from the navbar on every page. `noindex` is the directive that actually keeps a URL
// out of the index; a crawler only sees it if it can fetch the URL, so the header is the second
// layer for any crawler/path that ends up fetching one regardless (and a static header needs no
// JavaScript, unlike the per-page <meta name="robots"> the SPA can add at runtime).

// Every route in app.routes.ts that sits behind AuthGuard/AdminGuard/ProviderGuard, or that is
// otherwise not meant for a search result (auth flows, checkout). Keep in sync with
// app.routes.ts -- there is no single source of truth to derive this from automatically, since
// route guard membership isn't itself data the build can introspect.
//
// A path WITHOUT a trailing slash is a prefix in robots.txt (so '/messages' covers the inbox
// itself AND '/messages/:propertyId'); the SEO audit of 2026-10-03 found '/messages/' left the
// inbox URL itself unprotected, and /analytics, /language and /offline missing entirely.
export const PRIVATE_PATHS = [
  '/my-listings',
  '/my-agency',
  '/property-form',
  '/properties/edit/',
  '/favorites',
  '/saved-searches',
  '/notifications',
  '/visits',
  '/my-services',
  '/my-reports',
  '/checkout/',
  '/payments',
  '/profile',
  '/settings',
  '/messages',
  '/analytics',
  '/admin/',
  '/provider/',
  '/short-stay/bookings',
  '/short-stay/manage',
  '/investments/watchlist',
  '/search-requests',
  '/referrals',
  '/login',
  '/auth/',
  '/language',
  '/offline',
  '/not-authorized',
  // Never linked to directly (only reached via the '**' wildcard's client-side redirect) --
  // listed for the same reason as /not-authorized: a non-JS crawler fetching it raw sees no
  // per-page noindex meta tag (that's set by NotFoundPage at runtime), so robots.txt is its only
  // defense. This does NOT block crawling of the arbitrary dead URLs that redirect here --
  // Disallow matches the literal path a crawler requests, not the client-side destination a
  // redirect lands on.
  '/not-found',
  // Public profile pages show a person's name, photo and join date. They are public by design
  // (reachable from a listing), but are thin and personal -- not something to put in a search
  // index until the owner decides otherwise.
  '/users/',
  '/newsletter/'
];

/** Netlify `_headers` path patterns for one robots-style path: a prefix without a trailing slash
 *  needs both the exact path and everything below it; one with a trailing slash is just the
 *  subtree. */
export function headerPatternsFor(path) {
  return path.endsWith('/') ? [`${path}*`] : [path, `${path}/*`];
}

export function buildHeadersFile(paths = PRIVATE_PATHS) {
  const blocks = paths.flatMap(headerPatternsFor).map(pattern => `${pattern}\n  X-Robots-Tag: noindex, nofollow\n`);

  return (
    '# Generated by tools/generate-robots.mjs at build time from tools/lib/private-paths.mjs --\n' +
    '# edits here do not persist past the next build. Change PRIVATE_PATHS in that file instead.\n' +
    '# Static noindex for pages that must never be indexed; applies in every deploy context\n' +
    '# (these paths are private everywhere, unlike robots.txt/sitemap which differ per context).\n\n' +
    blocks.join('\n')
  );
}
