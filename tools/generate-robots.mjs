// Generates public/robots.txt at build time, before `ng build` copies `public/` into the
// bundle as a static asset (see angular.json's `assets` glob on `public`).
//
// Why generated rather than a single static file: this app has no server-side way to send a
// different robots.txt (or an X-Robots-Tag header) per deploy context -- Netlify's declarative
// config does not support per-context headers, which is exactly why context-specific behavior
// elsewhere in this project (the Angular build itself) is done via environment file replacement
// and build-command overrides instead (see netlify.toml's [context.staging], and
// tools/generate-env.mjs). This follows the same pattern: only Netlify's CONTEXT build variable
// (see tools/lib/deploy-context-guard.mjs for why only Netlify sets it) distinguishes a real
// Production deploy from everything else -- Staging, deploy previews, branch deploys, and any
// local build default to the safe "block everything" robots.txt, so a non-Production build can
// never accidentally become indexable for lack of an explicit opt-in.
//
// Output file is tracked (unlike env.generated.ts): the Production content is the actual,
// reviewable robots.txt for the real site, not a secret.

import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

import { PRIVATE_PATHS, buildHeadersFile } from './lib/private-paths.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outFile = join(__dirname, '..', 'public', 'robots.txt');
const headersFile = join(__dirname, '..', 'public', '_headers');

const PRODUCTION_SITE_URL = 'https://hudhudnest.com';

const GENERATED_COMMENT =
  '# Generated by tools/generate-robots.mjs at build time -- edits here do not persist past the\n' +
  '# next build. Change PRIVATE_PATHS in tools/lib/private-paths.mjs instead.\n';

function buildProductionRobotsTxt(siteUrl) {
  const disallowLines = PRIVATE_PATHS.map(path => `Disallow: ${path}`).join('\n');
  return `${GENERATED_COMMENT}User-agent: *\nAllow: /\n${disallowLines}\n\nSitemap: ${siteUrl}/sitemap.xml\n`;
}

const BLOCK_ALL_ROBOTS_TXT = `${GENERATED_COMMENT}User-agent: *\nDisallow: /\n`;

const context = (process.env.CONTEXT ?? '').trim();
const isProduction = context === 'production';

const content = isProduction
  ? buildProductionRobotsTxt(process.env.SITE_URL?.trim() || PRODUCTION_SITE_URL)
  : BLOCK_ALL_ROBOTS_TXT;

writeFileSync(outFile, content, 'utf8');
// Same private-path list, as a static noindex header -- identical in every deploy context.
writeFileSync(headersFile, buildHeadersFile(), 'utf8');

console.log(
  `[generate-robots] wrote ${outFile} — CONTEXT="${context || '(unset, e.g. local build)'}" → ` +
    `${isProduction ? 'indexable (Production)' : 'blocked (non-Production)'}`
);
